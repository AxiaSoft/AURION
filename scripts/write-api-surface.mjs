/* Writes docs/api-surface.json from the source. See api-surface.mjs. */
import fs from "node:fs";
import path from "node:path";
import { surface, ROOT } from "./api-surface.mjs";

const s = surface();
const out = {
  _comment: "Generated by `npm run api:surface` from backend/src/index.js and "
    + "engine/aurion/api/server.py. Do not edit by hand. This is the contract the "
    + "native desk is written against; tests/api-surface.test.cjs fails when it "
    + "drifts from the source.",
  generatedFrom: ["backend/src/index.js", "engine/aurion/api/server.py"],
  counts: s.counts,
  routes: s.routes,
  engineRoutes: s.engineRoutes,
};
const file = path.join(ROOT, "docs", "api-surface.json");
fs.mkdirSync(path.dirname(file), { recursive: true });
fs.writeFileSync(file, JSON.stringify(out, null, 2) + "\n");
console.log(`docs/api-surface.json: ${s.routes.length} /api routes, ${s.engineRoutes.length} /v1 routes`);
if (s.unserved.length) console.log("UNSERVED:", s.unserved.join(", "));
if (s.dangling.length) console.log("DANGLING:", s.dangling.map(d => `${d.api}->${d.engine}`).join(", "));
