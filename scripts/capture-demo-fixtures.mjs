/**
 * Capture the desk's own API responses into the demo fixture file.
 *
 * The GitHub Pages build has no backend and no engine, so the desk there is
 * fed by apps/web/js/demo.js replaying canned responses.  Those responses are
 * captured from a real running desk rather than hand-written, because the
 * shapes are large, nested, and quietly load-bearing -- app.js reads fields
 * like strategy.auto_limit.left and prop.profile.label.fa, and a hand-made
 * fixture drifts from the real one the first time somebody adds a field.
 *
 * Usage, with the desk running on 8080:
 *
 *   node scripts/capture-demo-fixtures.mjs
 *   node scripts/capture-demo-fixtures.mjs --base http://127.0.0.1:8080
 *
 * It signs in through the freemium gate exactly as the browser does, so what
 * lands in the fixture is what a free visitor would really have seen.
 */

import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, "..");
const OUT = path.join(ROOT, "apps", "web", "demo", "fixtures.js");

const argBase = process.argv.indexOf("--base");
const BASE = argBase > -1 ? process.argv[argBase + 1] : "http://127.0.0.1:8080";

// GET endpoints the desk calls while a visitor clicks around.  Anything that
// writes is deliberately absent: the demo refuses those rather than faking a
// success, so there is nothing to capture for them.
const PATHS = [
  "/api/meta",
  "/api/license",
  "/api/snapshot",
  "/api/symbols",
  "/api/market/session",
  "/api/news",
  "/api/prop",
  "/api/agents",
  "/api/config",
  "/api/history?limit=400",
  "/api/logs?limit=200",
  "/api/logs?limit=400",
  "/api/access?limit=80",
  "/api/users",
  "/api/telegram",
  "/api/database",
  "/api/billing/plans",
  "/api/billing/history",
  "/api/updates",
  "/api/strategies/template",
  "/api/system/update/state",
  "/api/system/update/settings",
  "/api/host-logs",
];

async function main() {
  const gate = await fetch(`${BASE}/api/auth/license-session`, {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify({ mode: "freemium" }),
  }).then((r) => r.json());

  if (!gate.ok) {
    console.error(`gate refused: ${gate.error || "unknown"} -- is the desk running on ${BASE}?`);
    process.exit(1);
  }
  const token = gate.data.token;

  const out = {};
  for (const p of PATHS) {
    const res = await fetch(BASE + p, { headers: { authorization: `Bearer ${token}` } });
    const text = await res.text();
    let json;
    try {
      json = JSON.parse(text);
    } catch {
      console.warn(`skip ${p} -- not JSON (http ${res.status})`);
      continue;
    }
    out[p] = json;
    console.log(`${String(res.status).padEnd(4)} ${p}  ${text.length} bytes`);
  }

  // Written as a script that assigns a global, not as .json.  demo.js needs
  // the fixtures before app.js boots, and a <script> tag is the only way to
  // get a synchronous load that also survives being opened from file://,
  // where fetch and XMLHttpRequest on a sibling file are blocked outright.
  const banner = [
    "/* Generated by scripts/capture-demo-fixtures.mjs -- do not edit by hand.",
    " *",
    " * Captured responses from a real AURION desk, replayed by js/demo.js so",
    " * the GitHub Pages build has something to show.  Regenerate with the desk",
    " * running:  node scripts/capture-demo-fixtures.mjs",
    " */",
    "window.AURION_DEMO_FIXTURES = ",
  ].join("\n");

  await fs.mkdir(path.dirname(OUT), { recursive: true });
  await fs.writeFile(OUT, banner + JSON.stringify(out, null, 1) + ";\n");
  const size = (await fs.stat(OUT)).size;
  console.log(`\nwrote ${path.relative(ROOT, OUT)} -- ${Object.keys(out).length} endpoints, ${(size / 1024).toFixed(0)} KB`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
