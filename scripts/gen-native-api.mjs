/**
 * The native desk's API client, generated from docs/api-surface.json.
 *
 * 115 routes is 115 chances to mistype a path, and a mistyped path is
 * a 404 that nothing catches until a trader presses the button. The
 * manifest is already read out of the backend's own source and already
 * guarded by tests/api-surface.test.cjs, so the client is generated
 * from it rather than written by hand.
 *
 * That makes the whole surface exactly as correct as the manifest, and
 * the manifest exactly as correct as the backend. There is no third
 * place for the three of them to disagree.
 *
 * Regenerate with `npm run native:api`. tests/native-contract.test.cjs
 * fails when the checked-in file drifts from the manifest.
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const MANIFEST = path.join(ROOT, "docs", "api-surface.json");
const OUT = path.join(ROOT, "apps", "native", "Aurion.Core", "Api", "AurionApi.g.cs");

/** "/api/system/update/state" -> "SystemUpdateState" */
function methodName(verb, route) {
  const parts = route
    .replace(/^\/api\/?/, "")
    .split("/")
    .filter((s) => s && !s.startsWith(":"))
    .map((s) => s.replace(/[^A-Za-z0-9]+(.)?/g, (_, c) => (c ? c.toUpperCase() : ""))) 
    .map((s) => s.charAt(0).toUpperCase() + s.slice(1));
  const base = parts.join("") || "Root";
  return (verb === "GET" ? "Get" : verb === "POST" ? "Post"
    : verb === "PUT" ? "Put" : "Delete") + base;
}

/** ":id" segments become method parameters, in order. */
function paramsOf(route) {
  return route.split("/").filter((s) => s.startsWith(":")).map((s) => {
    const raw = s.slice(1);
    return { raw, cs: raw.replace(/[^A-Za-z0-9]/g, "") || "arg" };
  });
}

function pathExpression(route, params) {
  if (!params.length) return `"${route}"`;
  let expr = route;
  for (const p of params) {
    expr = expr.replace(`:${p.raw}`, `{Uri.EscapeDataString(${p.cs})}`);
  }
  return `$"${expr}"`;
}

function generate() {
  const manifest = JSON.parse(fs.readFileSync(MANIFEST, "utf8"));
  const seen = new Set();
  const methods = [];

  for (const route of manifest.routes) {
    for (const verb of route.methods) {
      if (!["GET", "POST", "PUT", "DELETE"].includes(verb)) continue;
      let name = methodName(verb, route.path);
      // Two routes can reduce to the same name once parameters are
      // dropped (/api/users and /api/users/:id/:off). Keep both, and
      // make the difference visible in the name rather than silently
      // losing one.
      if (seen.has(name)) {
        const extra = paramsOf(route.path).map((p) =>
          p.cs.charAt(0).toUpperCase() + p.cs.slice(1)).join("");
        name = name + "By" + (extra || "Path");
      }
      if (seen.has(name)) continue;
      seen.add(name);

      const params = paramsOf(route.path);
      const args = params.map((p) => `string ${p.cs}`);
      if (verb !== "GET") args.push("object? body = null");
      args.push("CancellationToken ct = default");

      const engine = route.engine.length ? route.engine.join(", ") : null;
      methods.push({
        name, verb, route: route.path, engine,
        args: args.join(", "),
        call: verb === "GET"
          ? `GetAsync(${pathExpression(route.path, params)}, ct)`
          : `SendAsync(HttpMethod.${verb === "POST" ? "Post" : verb === "PUT" ? "Put" : "Delete"}, ${pathExpression(route.path, params)}, body, ct)`,
      });
    }
  }

  methods.sort((a, b) => a.name.localeCompare(b.name));

  const head = `// <auto-generated>
//
//     Generated by scripts/gen-native-api.mjs from docs/api-surface.json.
//     Do not edit by hand - run \`npm run native:api\` instead.
//
//     115 routes is 115 chances to mistype a path, and a mistyped path
//     is a 404 that nothing catches until a trader presses the button.
//     The manifest is read out of the backend's own source and guarded
//     by tests/api-surface.test.cjs, so this file is as correct as the
//     backend is, with no third place for them to disagree.
//
//     Each method names the engine route behind it, where there is one.
//     Routes with no engine route are served by the backend itself.
//
// </auto-generated>

using System;
using System.Net.Http;
using System.Text.Json.Nodes;
using System.Threading;
using System.Threading.Tasks;

namespace Aurion.Core.Api;

/// <summary>Every route the desk can reach, one method each.</summary>
public sealed partial class AurionApi
{
`;

  const body = methods.map((m) => {
    const note = m.engine ? `    /// <summary>${m.verb} ${m.route} &#8594; ${m.engine}</summary>`
      : `    /// <summary>${m.verb} ${m.route} (served by the backend itself)</summary>`;
    return `${note}\n    public Task<JsonNode?> ${m.name}Async(${m.args})\n        => ${m.call};\n`;
  }).join("\n");

  const tail = `}\n`;
  return { text: head + body + tail, count: methods.length };
}

// No side effects on import, and that is load-bearing rather than
// tidiness. This module used to generate AND WRITE the file at import
// time. tests/native-contract.test.cjs imports it to compare the
// checked-in file against a fresh generation - so the import repaired
// the file a moment before the comparison read it, and the check could
// never fail. It was caught by hand-editing a route path and watching
// the guard pass. The writer lives in write-native-api.mjs now.
export { generate, OUT };
